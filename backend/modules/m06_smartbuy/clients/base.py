from typing import Protocol


class Clients(Protocol):
    # M1 · wardrobe digitiser (BO3)
    def classify(self, image: str) -> dict: ...
    def similar(self, user_id: str, embedding: list[float], k: int) -> list[dict]: ...
    def count_type(self, user_id: str, subcategory: str) -> int: ...
    # M2 · recommendation engine (BO1/BO2)
    def recommend_with(self, user_id: str, candidate: dict) -> list[dict]: ...
    def items(self, user_id: str) -> list[dict]: ...
    # M5 · style profile (BO4) — gaps + personal goals
    def gaps(self, user_id: str) -> list[str]: ...
    def goals(self, user_id: str) -> dict: ...
    def set_goals(self, user_id: str, goals: dict) -> dict: ...
    # M7 · local catalogue (BO6)
    def catalogue_search(self, category: str, colour: str | None, max_price: float | None) -> list[dict]: ...
    # M8 · LLM layer (BO8)
    def explain(self, facts: dict) -> str: ...
