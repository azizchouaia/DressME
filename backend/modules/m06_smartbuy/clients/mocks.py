"""Fixed-data mocks of M1, M2, M5, M7, M8.

Data: mocks/*_demo.json (tiny hand-made set, user 'usr_demo') + ml/data/bo5/synthetic/
(generated by `python -m modules.m06_smartbuy.synthetic`). A candidate can also be built on the fly:
probe_image = "custom:<subcategory>:<colour>"  (used by the web UI).
"""

import json
from pathlib import Path

import numpy as np

from .. import synthetic as syn

HERE = Path(__file__).resolve().parent.parent
MOCKS = HERE / "mocks"
DATA = HERE.parent.parent.parent / "ml" / "data" / "bo5"


def _load(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def _cos(a, b):
    a, b = np.asarray(a, float), np.asarray(b, float)
    n = min(len(a), len(b))
    a, b = a[:n], b[:n]
    return float(a @ b / (np.linalg.norm(a) * np.linalg.norm(b) + 1e-9))


def _complete(x: dict, folder: Path) -> dict:
    """Real data may come without embedding / category: fill them from tags or from the photo."""
    if not x.get("subcategory") and x.get("image"):
        from .. import vision
        ai = vision.analyze((folder / "images" / x["image"]).read_bytes())
        x.update(subcategory=ai["subcategory"], colour=ai["colour"])
    x.setdefault("category", syn.TYPES[x["subcategory"]][0])
    x.setdefault("label", syn.label(f"{x['colour']} {x['subcategory']}"))
    if not x.get("embedding"):
        x["embedding"] = syn.embed(x["subcategory"], x["colour"])
    return x


class MockClients:
    def __init__(self, dataset: str = "synthetic"):
        demo_w = _load(MOCKS / "wardrobe_demo.json")
        self.wardrobes = {demo_w["user_id"]: demo_w}
        self.candidates = {c["id"]: {**c, "demo": True} for c in _load(MOCKS / "candidates_demo.json")}
        folder = DATA / dataset
        self._goals_file = folder / "goals.json"   # mock of M5's goal store
        self._goals = _load(self._goals_file) or {}
        for w in _load(folder / "wardrobes.json") or []:
            w["items"] = [_complete(i, folder) for i in w["items"]]
            w.setdefault("gaps", [])
            self.wardrobes[w["user_id"]] = w
        for c in _load(folder / "candidates.json") or []:
            self.candidates[c["id"]] = _complete(c, folder)

    def _items(self, user_id):
        if user_id not in self.wardrobes:
            raise ValueError(f"mock: unknown user '{user_id}'. Known: {list(self.wardrobes)}")
        return self.wardrobes[user_id]["items"]

    # ---------------- M1 · wardrobe digitiser
    def classify(self, image: str) -> dict:
        if image.startswith("custom:"):
            _, sub, col = image.split(":")
            return {"id": image, "category": syn.TYPES[sub][0], "subcategory": sub, "colour": col,
                    "embedding": syn.embed(sub, col), "label": syn.label(f"{col} {sub}")}
        key = Path(image).stem
        if key not in self.candidates:
            raise ValueError(f"mock: unknown candidate '{key}'")
        c = self.candidates[key]
        return {"id": key, "category": c["category"], "subcategory": c["subcategory"], "colour": c["colour"],
                "embedding": c["embedding"], "label": c["label"]}

    def similar(self, user_id, embedding, k):
        sims = [{"item_id": it["id"], "label": it["label"], "category": it["category"],
                 "subcategory": it["subcategory"], "colour": it["colour"],
                 "similarity": round(max(0.0, _cos(embedding, it["embedding"])), 3)}
                for it in self._items(user_id)]
        return sorted(sims, key=lambda s: -s["similarity"])[:k]

    def items(self, user_id):
        return self._items(user_id)

    def count_type(self, user_id, subcategory):
        return sum(it["subcategory"] == subcategory for it in self._items(user_id))

    # ---------------- M2 · recommendation engine (stand-in rules)
    def recommend_with(self, user_id, candidate):
        c = self.candidates.get(candidate.get("id", ""))
        if c and c.get("demo"):  # hand-made demo set keeps its own rule
            goes = set(c.get("goes_with", []))
            slots = syn.SLOTS[c["category"]]
            items = self._items(user_id)
            pools = [[it for it in items if it["category"] == s and it["colour"] in goes] for s in slots]
            if len(pools) == 1:
                return [{"items": [a["id"]]} for a in pools[0]]
            return [{"items": [a["id"], b["id"]]} for a in pools[0] for b in pools[1]]
        return [{"items": o} for o in syn.combos(candidate, self._items(user_id))]

    # ---------------- M5 · style profile
    def gaps(self, user_id):
        return self.wardrobes.get(user_id, {}).get("gaps", [])

    def goals(self, user_id):
        return self._goals.get(user_id, {"templates": [], "budget": {}})

    def set_goals(self, user_id, goals):
        self._goals[user_id] = goals
        self._goals_file.parent.mkdir(parents=True, exist_ok=True)
        self._goals_file.write_text(json.dumps(self._goals, indent=1), encoding="utf-8")
        return goals

    # ---------------- M7 · local catalogue
    def catalogue_search(self, category, colour, max_price):
        return []  # BO5 uses partners.json (M13) for now

    # ---------------- M8 · LLM layer
    def explain(self, facts):
        v = {"buy": "Good buy", "think": "Think twice", "skip": "Skip it"}[facts["verdict"]]
        return f"{v}: " + "; ".join(facts["reasons"][:3]) + "."
